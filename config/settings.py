# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# SQLite locally (zero setup, matches the README's local-dev instructions).
# In production — Vercel's serverless functions have no persistent disk,
# so a SQLite file wouldn't survive between requests — set DATABASE_URL
# (Vercel's Postgres/Neon integration injects POSTGRES_URL automatically;
# either name is read here) to switch to Postgres with no code changes.
# The DPIA wizard's multi-step state lives in the database-backed session
# store (Django's default), so it survives across serverless invocations
# the same way any other model data does — no serverless-specific
# handling needed beyond having a real database configured.
_database_url = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")

if _database_url:
    DATABASES = {"default": dj_database_url.parse(_database_url, conn_max_age=600)}
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": str(BASE_DIR / "db.sqlite3"),
        }
    }


# Cache — where the rate limits on PDF export and admin login
# (dpia/views.py, dpia/admin.py) keep their counters. Django's default
# in-memory cache is per process, and on Vercel every serverless instance
# is its own process, so each one would count separately and the limits
# would barely apply. With a real database configured, the counters live
# in a Postgres table instead, shared by every instance. The table is
# created by `manage.py createcachetable` (see the README's deployment
# steps); locally and in tests, no DATABASE_URL means this block is
# skipped and Django falls back to its default per-process in-memory
# cache, which is fine since there's only one process to share counters
# across.
if _database_url:
    CACHES = {
        "default": {
            "BACKEND": "django.core.cache.backends.db.DatabaseCache",
            "LOCATION": "django_cache",
        }
    }


